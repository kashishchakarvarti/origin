function buildExtraProductWords(): string[] {
  const words = new Set<string>();
  Object.values(PRODUCT_TYPES).forEach((types) => types.forEach((t) => words.add(t)));
  PRODUCT_DESCRIPTORS.forEach((d) => words.add(d));
  BRAND_PREFIXES.forEach((p) => words.add(p));
  BRAND_SUFFIXES.forEach((s) => words.add(s));
  CATEGORIES.forEach((c) => words.add(c));
  COUNTRIES.forEach((c) => words.add(c));
  INCLUDED_SERVICES.forEach((s) => words.add(s));
  MISSION_STEPS.forEach((s) => words.add(s));
  return [...words].sort((a, b) => b.length - a.length);
}

const SORTED_TOKENS = buildExtraProductWords();

export function getDictionary(code: LanguageCode | string | undefined): Dict {
  const lang = (code && code in UI ? code : "en") as LanguageCode;
  return {
    ...enUI,
    ...AUDIENCE_UI.en,
    ...EXTRA_UI.en,
    ...UI[lang],
    ...AUDIENCE_UI[lang],
    ...EXTRA_UI[lang],
  };
}

export function translateKey(
  key: string,
  code: LanguageCode | string | undefined,
  vars?: Record<string, string | number>
): string {
  const dict = getDictionary(code);
  let text = dict[key] ?? enUI[key] ?? key;
  if (vars) {
    for (const [k, v] of Object.entries(vars)) {
      text = text.replaceAll(`{${k}}`, String(v));
    }
  }
  return text;
}

function translateToken(token: string, code: LanguageCode): string {
  if (code === "en") return token;
  const map = WORD_MAPS[code];
  return map[token] ?? token;
}

/** Translate product, business, category, country, and service names. */
export function translateName(name: string | undefined | null, code: LanguageCode | string | undefined): string {
  if (!name) return "";
  const lang = (code && code in UI ? code : "en") as LanguageCode;
  if (lang === "en") return name;

  const hasTm = name.includes("™");
  const clean = name.replace("™", "").trim();

  // Exact phrase match first (e.g. "Pillow Set")
  const exact = translateToken(clean, lang);
  if (exact !== clean) return exact + (hasTm ? "™" : "");

  // Brand-style concatenated names: SmartSleep
  if (!clean.includes(" ")) {
    for (const prefix of [...BRAND_PREFIXES].sort((a, b) => b.length - a.length)) {
      if (clean.startsWith(prefix) && clean.length > prefix.length) {
        const suffix = clean.slice(prefix.length);
        return `${translateToken(prefix, lang)}${translateToken(suffix, lang)}${hasTm ? "™" : ""}`;
      }
    }
    return clean + (hasTm ? "™" : "");
  }

  // Multi-word product names: "Premium Pillow Set"
  let remaining = clean;
  const parts: string[] = [];
  while (remaining.length > 0) {
    let matched = false;
    for (const token of SORTED_TOKENS) {
      if (remaining === token || remaining.startsWith(`${token} `)) {
        parts.push(translateToken(token, lang));
        remaining = remaining.slice(token.length).trimStart();
        matched = true;
        break;
      }
    }
    if (!matched) {
      const [word, ...rest] = remaining.split(/\s+/);
      parts.push(translateToken(word, lang));
      remaining = rest.join(" ");
    }
  }

  return parts.join(" ") + (hasTm ? "™" : "");
}

